"""Small PostgreSQL compatibility layer for the existing SQL repository API.

Enabled only when RAG_DATABASE_URL is set. psycopg is an optional dependency.
"""
import os
import re
from contextlib import contextmanager

try:
    import psycopg
    from psycopg.rows import dict_row
    IntegrityError = psycopg.IntegrityError
except ImportError:
    psycopg = None
    class IntegrityError(Exception):
        pass

ID_TABLES = {'roles','users','knowledge_bases','documents','chunks','conversations','messages',
             'report_templates','report_tasks','report_sections','audit_logs','jobs','job_events',
             'model_calls','document_events','report_section_history','template_imports',
             'report_candidates','report_releases'}


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


class Cursor:
    def __init__(self, inner, lastrowid=None):
        self.inner = inner
        self.lastrowid = lastrowid

    @property
    def rowcount(self):
        return self.inner.rowcount

    def fetchone(self):
        value = self.inner.fetchone()
        return Row(value) if value is not None else None

    def fetchall(self):
        return [Row(value) for value in self.inner.fetchall()]

    def __iter__(self):
        for value in self.inner:
            yield Row(value)


class Connection:
    def __init__(self, inner):
        self.inner = inner

    def execute(self, sql, params=()):
        statement = sql.strip()
        if statement.upper() == 'BEGIN IMMEDIATE':
            # Preserve SQLite's serialized critical-section semantics during migration.
            return self.inner.execute('SELECT pg_advisory_xact_lock(25102026)')
        match = re.fullmatch(r'PRAGMA table_info\((\w+)\)', statement, re.I)
        if match:
            cur = self.inner.execute('''SELECT column_name AS name FROM information_schema.columns
                WHERE table_schema=current_schema() AND table_name=%s''', (match.group(1),))
            return Cursor(cur)
        statement = re.sub(r'^INSERT OR IGNORE INTO', 'INSERT INTO', statement, flags=re.I)
        ignore = sql.lstrip().upper().startswith('INSERT OR IGNORE INTO')
        if ignore:
            statement += ' ON CONFLICT DO NOTHING'
        if statement.upper().startswith('INSERT OR REPLACE INTO EMBEDDING_CACHE'):
            statement = 'INSERT INTO embedding_cache(namespace,sha256,vector) VALUES(?,?,?) ON CONFLICT (namespace,sha256) DO UPDATE SET vector=EXCLUDED.vector'
        if statement.upper().startswith('INSERT OR REPLACE INTO SYSTEM_SETTINGS'):
            statement = 'INSERT INTO system_settings(id,value,revision,updated_at,updated_by) VALUES(1,?,?,?,?) ON CONFLICT (id) DO UPDATE SET value=EXCLUDED.value,revision=EXCLUDED.revision,updated_at=EXCLUDED.updated_at,updated_by=EXCLUDED.updated_by'
        insert = re.match(r'INSERT\s+INTO\s+(\w+)', statement, re.I)
        returns_id = bool(insert and insert.group(1).lower() in ID_TABLES and 'RETURNING' not in statement.upper())
        if returns_id:
            statement += ' RETURNING id'
        statement = statement.replace('?', '%s')
        params = tuple(int(value) if isinstance(value, bool) else value for value in params)
        cur = self.inner.execute(statement, params)
        lastrowid = cur.fetchone()['id'] if returns_id else None
        return Cursor(cur, lastrowid)

    def executemany(self, sql, values):
        statement = sql.strip()
        if statement.upper().startswith('INSERT OR REPLACE INTO EMBEDDING_CACHE'):
            statement = 'INSERT INTO embedding_cache(namespace,sha256,vector) VALUES(?,?,?) ON CONFLICT (namespace,sha256) DO UPDATE SET vector=EXCLUDED.vector'
        statement = statement.replace('?', '%s')
        cur = self.inner.cursor()
        cur.executemany(statement, [tuple(int(value) if isinstance(value, bool) else value for value in row) for row in values])
        return Cursor(cur)

    def executescript(self, script):
        for statement in script.split(';'):
            statement = statement.strip()
            if statement:
                statement = re.sub(r'INTEGER PRIMARY KEY', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', statement)
                self.execute(statement)

    def align_sequences(self):
        for table in ID_TABLES:
            self.inner.execute(f"SELECT setval(pg_get_serial_sequence('{table}','id'), (SELECT COALESCE(MAX(id),0)+1 FROM {table}), false)")


@contextmanager
def connect():
    if psycopg is None:
        raise RuntimeError('PostgreSQL 模式需安装 requirements-server.txt')
    with psycopg.connect(os.environ['RAG_DATABASE_URL'], row_factory=dict_row) as raw:
        yield Connection(raw)
